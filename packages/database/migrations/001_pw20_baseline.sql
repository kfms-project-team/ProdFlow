CREATE TABLE accounts_user (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(150) NOT NULL UNIQUE,
  password varchar(128) NOT NULL,
  first_name varchar(150) NOT NULL DEFAULT '', last_name varchar(150) NOT NULL DEFAULT '',
  email varchar(254) NOT NULL DEFAULT '', is_active boolean NOT NULL DEFAULT true,
  is_staff boolean NOT NULL DEFAULT false, is_superuser boolean NOT NULL DEFAULT false,
  date_joined timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, last_login timestamptz
);
CREATE TABLE employees (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id bigint NOT NULL UNIQUE REFERENCES accounts_user(id) ON DELETE RESTRICT,
  employee_number varchar(20) NOT NULL UNIQUE, phone varchar(30), position varchar(80),
  is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(150) NOT NULL, contact_name varchar(100), email varchar(254), phone varchar(30),
  notes text, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE workstations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code varchar(20) NOT NULL UNIQUE, name varchar(100) NOT NULL, description text, location varchar(150),
  is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE projects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_number varchar(30) NOT NULL UNIQUE, name varchar(150) NOT NULL, description text,
  customer_id bigint REFERENCES customers(id) ON DELETE SET NULL,
  created_by_id bigint NOT NULL REFERENCES accounts_user(id) ON DELETE RESTRICT,
  status varchar(20) NOT NULL DEFAULT 'draft', priority varchar(10) NOT NULL DEFAULT 'normal',
  planned_start_date date, due_date date,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, completed_at timestamptz,
  CONSTRAINT ck_project_status CHECK (status IN ('draft','planned','in_progress','on_hold','completed','cancelled')),
  CONSTRAINT ck_project_priority CHECK (priority IN ('low','normal','high','urgent')),
  CONSTRAINT ck_project_dates CHECK (due_date >= planned_start_date)
);
CREATE TABLE tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id bigint NOT NULL REFERENCES projects(id) ON DELETE RESTRICT,
  workstation_id bigint NOT NULL REFERENCES workstations(id) ON DELETE RESTRICT,
  name varchar(150) NOT NULL, description text, sequence_no integer NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'planned', planned_minutes integer NOT NULL DEFAULT 0,
  due_at timestamptz, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, completed_at timestamptz,
  UNIQUE(project_id, sequence_no),
  CONSTRAINT ck_task_status CHECK (status IN ('planned','in_progress','blocked','completed','cancelled')),
  CONSTRAINT ck_task_minutes CHECK (planned_minutes >= 0),
  CONSTRAINT ck_task_sequence CHECK (sequence_no > 0)
);
CREATE TABLE task_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE RESTRICT,
  employee_id bigint NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
  assigned_by_id bigint NOT NULL REFERENCES accounts_user(id) ON DELETE RESTRICT,
  assigned_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP, unassigned_at timestamptz,
  CONSTRAINT ck_assignment_dates CHECK (unassigned_at > assigned_at)
);
CREATE UNIQUE INDEX uq_assignment_active ON task_assignments(task_id, employee_id) WHERE unassigned_at IS NULL;
CREATE TABLE qr_points (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(), point_type varchar(20) NOT NULL,
  name varchar(100) NOT NULL,
  workstation_id bigint UNIQUE REFERENCES workstations(id) ON DELETE RESTRICT,
  is_active boolean NOT NULL DEFAULT true, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_qr_point_type CHECK (point_type IN ('entrance','workstation')),
  CONSTRAINT ck_qr_point_station CHECK (
    (point_type = 'entrance' AND workstation_id IS NULL) OR
    (point_type = 'workstation' AND workstation_id IS NOT NULL))
);
CREATE TABLE attendance_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
  check_in_at timestamptz NOT NULL, check_out_at timestamptz,
  check_in_qr_point_id bigint REFERENCES qr_points(id) ON DELETE SET NULL,
  check_out_qr_point_id bigint REFERENCES qr_points(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_attendance_dates CHECK (check_out_at > check_in_at)
);
CREATE UNIQUE INDEX uq_attendance_one_open ON attendance_records(employee_id) WHERE check_out_at IS NULL;
CREATE TABLE attendance_breaks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendance_id bigint NOT NULL REFERENCES attendance_records(id) ON DELETE RESTRICT,
  break_type varchar(20) NOT NULL, started_at timestamptz NOT NULL, ended_at timestamptz,
  note text, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_break_type CHECK (break_type IN ('short','meal','other')),
  CONSTRAINT ck_break_dates CHECK (ended_at > started_at)
);
CREATE UNIQUE INDEX uq_break_one_open ON attendance_breaks(attendance_id) WHERE ended_at IS NULL;
CREATE TABLE work_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id bigint NOT NULL REFERENCES employees(id) ON DELETE RESTRICT,
  task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE RESTRICT,
  started_qr_point_id bigint NOT NULL REFERENCES qr_points(id) ON DELETE RESTRICT,
  started_at timestamptz NOT NULL, ended_at timestamptz, end_reason varchar(20),
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT ck_work_dates CHECK (ended_at > started_at),
  CONSTRAINT ck_work_reason CHECK (end_reason IN ('break','task_switch','task_completed','shift_end','other'))
);
CREATE UNIQUE INDEX uq_work_session_one_open ON work_sessions(employee_id) WHERE ended_at IS NULL;
CREATE TABLE audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_user_id bigint REFERENCES accounts_user(id) ON DELETE SET NULL,
  action varchar(50) NOT NULL, entity_type varchar(50) NOT NULL, entity_id bigint NOT NULL,
  reason text, old_data jsonb, new_data jsonb,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
