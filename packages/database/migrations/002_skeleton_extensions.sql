-- Proposed extensions for the NEW development database. Does not modify PW-20.
ALTER TABLE accounts_user ADD COLUMN role varchar(10) NOT NULL DEFAULT 'worker'
  CHECK (role IN ('worker','manager','admin'));
CREATE TABLE teams (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE employees ADD COLUMN team_id bigint REFERENCES teams(id) ON DELETE RESTRICT;
ALTER TABLE attendance_records ADD COLUMN version integer NOT NULL DEFAULT 1 CHECK (version > 0);
ALTER TABLE attendance_records ADD CONSTRAINT uq_attendance_employee UNIQUE(id, employee_id);
ALTER TABLE work_sessions ADD COLUMN attendance_id bigint NOT NULL;
ALTER TABLE work_sessions ADD CONSTRAINT fk_work_attendance_employee
  FOREIGN KEY (attendance_id, employee_id) REFERENCES attendance_records(id, employee_id) ON DELETE RESTRICT;
ALTER TABLE work_sessions ADD COLUMN completed_units integer NOT NULL DEFAULT 0 CHECK (completed_units >= 0);
ALTER TABLE work_sessions ADD CONSTRAINT ck_work_end_pair CHECK (
  (ended_at IS NULL AND end_reason IS NULL) OR (ended_at IS NOT NULL AND end_reason IS NOT NULL));
ALTER TABLE audit_logs ADD CONSTRAINT ck_correction_reason CHECK (
  action NOT LIKE '%.correct' OR (reason IS NOT NULL AND length(trim(reason)) > 0));
CREATE TABLE auth_sessions (
  token_hash char(64) PRIMARY KEY,
  user_id bigint NOT NULL REFERENCES accounts_user(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at timestamptz NOT NULL CHECK (expires_at > created_at)
);
CREATE INDEX ix_auth_expiry ON auth_sessions(expires_at);
CREATE TABLE terminals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  qr_point_id bigint NOT NULL REFERENCES qr_points(id) ON DELETE RESTRICT,
  credential_hash char(64) NOT NULL UNIQUE,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE qr_challenges (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  token_hash char(64) NOT NULL UNIQUE,
  terminal_id bigint NOT NULL REFERENCES terminals(id) ON DELETE RESTRICT,
  issued_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at timestamptz NOT NULL CHECK (expires_at > issued_at)
);
CREATE INDEX ix_qr_expiry ON qr_challenges(expires_at);
CREATE TABLE operation_receipts (
  actor_user_id bigint NOT NULL REFERENCES accounts_user(id) ON DELETE RESTRICT,
  operation_id uuid NOT NULL,
  request_hash char(64) NOT NULL,
  result jsonb NOT NULL,
  accepted_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY(actor_user_id, operation_id)
);
CREATE INDEX ix_assignment_employee ON task_assignments(employee_id) WHERE unassigned_at IS NULL;
CREATE INDEX ix_work_task_time ON work_sessions(task_id, started_at);
CREATE INDEX ix_attendance_employee_time ON attendance_records(employee_id, check_in_at);
CREATE INDEX ix_audit_entity_time ON audit_logs(entity_type, entity_id, created_at);
CREATE OR REPLACE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN NEW.updated_at = CURRENT_TIMESTAMP; RETURN NEW; END;
$$;
CREATE TRIGGER touch_projects BEFORE UPDATE ON projects FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER touch_tasks BEFORE UPDATE ON tasks FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
CREATE TRIGGER touch_attendance BEFORE UPDATE ON attendance_records FOR EACH ROW EXECUTE FUNCTION touch_updated_at();
